const FALLBACK_WEAR = C({
  label: "Wayfarer",
  cloth: "#5b5a55",
  trim: "#a89a7c",
  leather: "#4e4032",
});

const FALLBACK_KIT = B({ label: "Wayfarer", belt: "plain", boots: "soft" });

const FALLBACK_SILHOUETTE = K({ label: "Adventurer" });

/** Resolve a hero's choices into a concrete outfit specification. */
export function wearFor(draft = {}) {
  const cultureId = typeof draft.culture === "string" ? draft.culture : draft.culture?.id;
  const backgroundId =
    typeof draft.background === "string" ? draft.background : draft.background?.id;
  const classId = draft.classId;
  return {
    cultureId: cultureId ?? null,
    backgroundId: backgroundId ?? null,
    classId: classId ?? null,
    wear: CULTURE_WEAR[cultureId] ?? FALLBACK_WEAR,
    kit: BACKGROUND_KIT[backgroundId] ?? FALLBACK_KIT,
    silhouette: CLASS_SILHOUETTE[classId] ?? FALLBACK_SILHOUETTE,
    known: {
      culture: cultureId in CULTURE_WEAR,
      background: backgroundId in BACKGROUND_KIT,
      class: classId in CLASS_SILHOUETTE,
    },
  };
}

/** Which choices in a catalog have no hand-authored entry, for coverage reporting. */
export function wardrobeGaps({ cultures = [], backgrounds = [], classes = [] }) {
  return {
    cultures: cultures.filter((id) => !(id in CULTURE_WEAR)),
    backgrounds: backgrounds.filter((id) => !(id in BACKGROUND_KIT)),
    classes: classes.filter((id) => !(id in CLASS_SILHOUETTE)),
  };
}
